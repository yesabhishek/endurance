#!/usr/bin/env bash
# Creates .env (for docker compose) and web/.env (for `npm run dev`) with fresh
# random secrets. Safe to re-run: existing non-empty values are kept.
set -euo pipefail

cd "$(dirname "$0")/.."

ROOT_ENV=".env"
WEB_ENV="web/.env"

random_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1"
  else
    node -e "console.log(require('crypto').randomBytes($1).toString('hex'))"
  fi
}

# get_value FILE KEY -> prints the value (empty if missing)
get_value() {
  local line
  line=$(grep -E "^$2=" "$1" 2>/dev/null | tail -n 1 || true)
  local value=${line#*=}
  value=${value%\"}
  value=${value#\"}
  printf '%s' "$value"
}

is_placeholder() {
  [[ -z "$1" || "$1" =~ (replace|change[-_\ ]?me|your[-_]|example|placeholder) ]]
}

# set_value FILE KEY VALUE -> replaces KEY=... or appends it
set_value() {
  local file=$1 key=$2 value=$3 tmp
  tmp=$(mktemp)
  if grep -qE "^$key=" "$file"; then
    awk -v k="$key" -v v="$value" 'BEGIN { FS = OFS = "=" } $1 == k { print k "=" v; next } { print }' "$file" >"$tmp"
  else
    cat "$file" >"$tmp"
    printf '%s=%s\n' "$key" "$value" >>"$tmp"
  fi
  cat "$tmp" >"$file"
  rm -f "$tmp"
}

ensure_secret() {
  local file=$1 key=$2 bytes=$3
  local current
  current=$(get_value "$file" "$key")
  if is_placeholder "$current"; then
    set_value "$file" "$key" "$(random_hex "$bytes")"
    echo "  generated $key"
  else
    echo "  kept existing $key"
  fi
}

umask 077

if [[ ! -f "$ROOT_ENV" ]]; then
  cp .env.example "$ROOT_ENV"
  echo "Created $ROOT_ENV from .env.example"
else
  echo "Updating $ROOT_ENV (existing values are kept)"
fi

ensure_secret "$ROOT_ENV" APP_SECRET 32
ensure_secret "$ROOT_ENV" POSTGRES_PASSWORD 24
ensure_secret "$ROOT_ENV" REDIS_PASSWORD 24
if [[ -z "$(get_value "$ROOT_ENV" APP_URL)" ]]; then set_value "$ROOT_ENV" APP_URL "http://localhost:3000"; fi
chmod 600 "$ROOT_ENV"

# web/.env lets `npm run dev` and the Prisma CLI reach the compose databases on localhost.
if [[ -f "$WEB_ENV" ]] && grep -qE '^DATABASE_URL="?file:' "$WEB_ENV"; then
  backup="$WEB_ENV.sqlite-backup"
  mv "$WEB_ENV" "$backup"
  echo "Moved the old SQLite-era $WEB_ENV to $backup"
fi

if [[ ! -f "$WEB_ENV" ]]; then
  pg=$(get_value "$ROOT_ENV" POSTGRES_PASSWORD)
  redis=$(get_value "$ROOT_ENV" REDIS_PASSWORD)
  cat >"$WEB_ENV" <<EOF
# Local development settings, generated by scripts/setup.sh. Do not commit.
DATABASE_URL=postgresql://endurance:${pg}@localhost:5432/endurance
REDIS_URL=redis://:${redis}@localhost:6379
APP_SECRET=$(get_value "$ROOT_ENV" APP_SECRET)
APP_URL=$(get_value "$ROOT_ENV" APP_URL)
GOOGLE_CLIENT_ID=$(get_value "$ROOT_ENV" GOOGLE_CLIENT_ID)
GOOGLE_CLIENT_SECRET=$(get_value "$ROOT_ENV" GOOGLE_CLIENT_SECRET)
EOF
  chmod 600 "$WEB_ENV"
  echo "Created $WEB_ENV for local development"
fi

cat <<'EOF'

Done. Next:
  docker compose up --build        # full stack at http://localhost:3000

Or, for development with hot reload:
  docker compose -f docker-compose.yml -f docker-compose.dev.yml up -d postgres redis
  cd web && npm install && npx prisma migrate deploy && npm run dev   # and `npm run worker` in another terminal

Then create your account, open Settings, add your Kite Connect app and an AI key.
EOF
